import fs from 'node:fs';
import assert from 'node:assert/strict';
const source = fs.readFileSync(new URL('./Remove-SyndocalData.ps1', import.meta.url), 'utf8');
const escaped = line => line.replaceAll('$', () => '$$').replaceAll('"', '$\\"');
const writes = source.trimEnd().split(/\r?\n/).map(line => `  FileWrite $R8 "${escaped(line)}$\\r$\\n"`).join('\n');
const hook = `; Generated by tools/distribution/generate-installer-hooks.mjs. No installed helper payload.
!macro SYNDOCAL_DATA_CLEANUP VALIDATE
  InitPluginsDir
  FileOpen $R8 "$PLUGINSDIR\\syndocal-cleanup.ps1" w
${writes}
  FileClose $R8
  nsExec::ExecToLog '\"$SYSDIR\\WindowsPowerShell\\v1.0\\powershell.exe\" -NoLogo -NoProfile -NonInteractive -ExecutionPolicy Bypass -File \"$PLUGINSDIR\\syndocal-cleanup.ps1\" \${VALIDATE}'
  Pop $R8
  \${If} $R8 != 0
    MessageBox MB_ICONSTOP "Syndocal cleanup failed. Close Syndocal and retry with Remove-SyndocalData.ps1."
    SetErrorLevel 1
    Abort
  \${EndIf}
!macroend
!macro NSIS_HOOK_PREUNINSTALL
  \${If} $DeleteAppDataCheckboxState = 1
  \${AndIf} $UpdateMode <> 1
    !insertmacro SYNDOCAL_DATA_CLEANUP "-ValidateOnly"
  \${EndIf}
!macroend
!macro NSIS_HOOK_POSTUNINSTALL
  \${If} $DeleteAppDataCheckboxState = 1
  \${AndIf} $UpdateMode <> 1
    !insertmacro SYNDOCAL_DATA_CLEANUP ""
  \${EndIf}
!macroend
`;
const destination = new URL('../../app/src-tauri/installer-hooks.nsh', import.meta.url);
if (process.argv.includes('--write')) fs.writeFileSync(destination, hook);
else { assert.equal(fs.readFileSync(destination, 'utf8'), hook); console.log('installer cleanup hook matches reviewed helper'); }
