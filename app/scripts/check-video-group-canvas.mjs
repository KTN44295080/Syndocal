import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { typescriptFixtureModuleUrl } from "./typescript-fixture-module.mjs";
const { dragGroupTransform: drag, groupCanvasHandlePoint: point, nudgeGroupTransform: nudge } = await import(await typescriptFixtureModuleUrl(new URL("../src/videoGroupCanvasGeometry.ts", import.meta.url)));
const t = { x: 0.2, y: -0.1, scale_x: 0.8, scale_y: 0.4, rotation_deg: 0, crop_left: 0.1, crop_top: 0, crop_right: 0, crop_bottom: 0 };
const near = (actual, expected) => assert.ok(Math.abs(actual - expected) < 1e-10, `${actual} != ${expected}`);
const moved = drag(t, "move", { x: 0, y: 0 }, { x: 0.3, y: 0.2 }, false);
near(moved.x, 0.5); near(moved.y, 0.1); assert.equal(moved.crop_left, 0.1);
assert.equal(drag(t, "move", { x: 0, y: 0 }, { x: 5, y: -5 }, false).x, 1);
for (const [handle, sx, sy] of [["nw", -1, -1], ["ne", 1, -1], ["se", 1, 1], ["sw", -1, 1]]) {
  const start = point(t, handle);
  const scaled = drag(t, handle, start, { x: start.x + sx * 0.1, y: start.y + sy * 0.1 }, false);
  near(scaled.scale_x, 1); near(scaled.scale_y, 0.6);
  assert.equal(scaled.x, t.x); assert.equal(scaled.y, t.y);
  const locked = drag(t, handle, start, { x: start.x + sx * 0.2, y: start.y + sy * 0.3 }, true);
  near(locked.scale_x / locked.scale_y, 2);
}
const rotatedStart = { ...t, rotation_deg: 90 };
const corner = point(rotatedStart, "se");
near(corner.x, 0); near(corner.y, 0.3);
const scaled = drag(rotatedStart, "se", corner, { x: corner.x - 0.1, y: corner.y + 0.2 }, false);
near(scaled.scale_x, 1.2); near(scaled.scale_y, 0.6);
const start = { x: t.x + 0.5, y: t.y };
const end = { x: t.x + Math.cos(22 * Math.PI / 180), y: t.y + Math.sin(22 * Math.PI / 180) };
near(drag(t, "rotate", start, end, false).rotation_deg, 22);
near(drag(t, "rotate", start, end, true).rotation_deg, 15);
const turned = drag(t, "rotate", start, { x: t.x, y: t.y + 1 }, false);
assert.equal(turned.x, t.x); assert.equal(turned.y, t.y); near(turned.rotation_deg, 90);
const branch = drag({ ...t, rotation_deg: 170 }, "rotate", { x: t.x - 1, y: t.y + 0.01 }, { x: t.x - 1, y: t.y - 0.01 }, false);
assert.ok(branch.rotation_deg > 170 && branch.rotation_deg < 172, "atan branch crossing stays continuous");
const clamped = drag(t, "se", point(t, "se"), { x: 99, y: 99 }, true);
near(clamped.scale_x, 3); near(clamped.scale_y, 1.5);
assert.deepEqual(drag(t, "move", start, { x: NaN, y: 0 }, false), t);
near(nudge(t, "ArrowRight", false).x, 0.21); near(nudge(t, "ArrowDown", true).y, 0);
assert.equal(nudge({ ...t, x: 1 }, "ArrowRight", true).x, 1);
const native = await readFile(new URL("../src-tauri/src/main.rs", import.meta.url), "utf8");
const preview = native.slice(native.indexOf("fn get_debug_video_preview("), native.indexOf("fn get_debug_video_output_preview("));
assert.match(preview, /composition_id: Option<CompositionId>/);
assert.match(preview, /snapshot\.compositions\.retain\(\|composition\| composition\.id == composition_id\)/);
assert.match(preview, /if snapshot\.compositions\.is_empty\(\)/, "missing composition is rejected rather than showing the first composition");
const inspector = await readFile(new URL("../src/components/VideoGroupInspector.tsx", import.meta.url), "utf8");
assert.match(inspector, /onCommit=\{value => patch\(\{ transform: value \}\)\}/, "one final transform uses the inspector's existing catalog path");
console.log("PASS group canvas geometry: all corners, normalized renderer rotation/pivot, aspect lock/clamps, snapping, branch crossing, nudges, immutable invalid input; explicit preview composition rejection");
