type RenderState = { source: string; rendered: string };
const textStates = new WeakMap<Text, RenderState>();
const attributeStates = new WeakMap<Element, Map<string, RenderState>>();
const translatedAttributes = ["title", "aria-label", "aria-valuetext", "placeholder"] as const;

function localizeTextNode(node: Text, locale: UiLocale) {
  const parent = node.parentElement;
  if (!parent || parent.closest("script, style, textarea, [data-no-localize]")) return;
  const current = node.nodeValue ?? "";
  let state = textStates.get(node);
  if (!state || current !== state.rendered) {
    state = { source: current, rendered: current };
  }
  const rendered = translateUiText(state.source, locale);
  state.rendered = rendered;
  textStates.set(node, state);
  if (current !== rendered) node.nodeValue = rendered;
}

function localizeElementAttributes(element: Element, locale: UiLocale) {
  if (element.closest("script, style, textarea, [data-no-localize]")) return;
  let states = attributeStates.get(element);
  if (!states) {
    states = new Map();
    attributeStates.set(element, states);
  }
  for (const attribute of translatedAttributes) {
    if (!element.hasAttribute(attribute)) continue;
    const current = element.getAttribute(attribute) ?? "";
    let state = states.get(attribute);
    if (!state || current !== state.rendered) {
      state = { source: current, rendered: current };
    }
    const rendered = translateUiText(state.source, locale);
    state.rendered = rendered;
    states.set(attribute, state);
    if (current !== rendered) element.setAttribute(attribute, rendered);
  }
}

function localizeNode(node: Node, locale: UiLocale) {
  if (node instanceof Text) {
    localizeTextNode(node, locale);
    return;
  }
  if (!(node instanceof Element)) return;
  localizeElementAttributes(node, locale);
  const walker = document.createTreeWalker(node, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
  let descendant = walker.nextNode();
  while (descendant) {
    if (descendant instanceof Text) localizeTextNode(descendant, locale);
    else if (descendant instanceof Element) localizeElementAttributes(descendant, locale);
    descendant = walker.nextNode();
  }
}

export function installUiLocalization(root: HTMLElement, getLocale: () => UiLocale) {
  let queued = false;
  const pending = new Set<Node>();
  const refresh = () => {
    document.documentElement.lang = getLocale() === "ja" ? "ja" : "en";
    localizeNode(root, getLocale());
  };
  const queuePending = () => {
    if (queued) return;
    queued = true;
    queueMicrotask(() => {
      queued = false;
      const locale = getLocale();
      document.documentElement.lang = locale === "ja" ? "ja" : "en";
      for (const node of pending) localizeNode(node, locale);
      pending.clear();
    });
  };
  const observer = new MutationObserver((mutations) => {
    for (const mutation of mutations) {
      if (mutation.type === "childList") {
        for (const node of mutation.addedNodes) pending.add(node);
      } else {
        pending.add(mutation.target);
      }
    }
    if (pending.size > 0) queuePending();
  });
  observer.observe(root, {
    subtree: true,
    childList: true,
    characterData: true,
    attributes: true,
    attributeFilter: [...translatedAttributes],
  });
  refresh();
  return {
    refresh,
    dispose: () => observer.disconnect(),
  };
}
