import assert from "node:assert/strict";
import fs from "node:fs/promises";
import ts from "../node_modules/typescript/lib/typescript.js";
const modules = new Map();
// Sibling modules (for example the Perform routing decoder) load from source too.
const load = async path => {
  const url = new URL(path, import.meta.url);
  if (modules.has(url.href)) return modules.get(url.href);
  const source = await fs.readFile(url, "utf8");
  const js = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
  const exports = {}; modules.set(url.href, exports);
  const required = {};
  for (const [, name] of js.matchAll(/require\("(\.[^"]+)"\)/g)) required[name] = await load(new URL(name + ".ts", url).href);
  Function("exports", "require", js)(exports, name => required[name]); return exports;
};
const { createMidiFaderInput, midiFaderConnection } = await load("../src/midiFaderInput.ts");
const { createFaderValueController } = await load("../src/createFaderValueController.ts");
let epoch = 8, values = {}, applied = 0;
const faders = createFaderValueController({ setValues: f => values = typeof f === "function" ? f(values) : f });
const input = createMidiFaderInput({ projectEpoch: () => epoch, apply: v => { applied++; faders.applyMidiInput(v); } });
const connection = { schema_version: 1, project_epoch: 8, input_session: 13 };
input.setConnection(midiFaderConnection(connection));
const event = { ...connection, sequence: 1, values: [{ fixture_id: 2, attribute: "Dimmer", value: 40000 }] };
assert.equal(input.accept(event), true);
assert.equal(values["2:Dimmer"], 40000, "received MIDI repaints without waiting for a poll");
const same = values;
values = faders.mergeSnapshotValues(values, { "2:Dimmer": 0 });
assert.equal(values, same, "older snapshot cannot immediately overwrite the event");
values = faders.mergeSnapshotValues(values, { "2:Dimmer": 40000 });
assert.equal(input.accept(event), false, "duplicate cannot replay");
assert.equal(input.accept({ ...event, sequence: 2, input_session: 12 }), false, "retired input cannot repaint");
assert.equal(input.accept({ ...event, sequence: 2, schema_version: 2 }), false);
assert.equal(input.accept({ ...event, sequence: 2, values: [{ ...event.values[0], value: -1 }] }), false);
epoch = 9;
assert.equal(input.accept({ ...event, sequence: 2 }), false, "old project cannot repaint");
input.setConnection(null);
epoch = 8;
assert.equal(input.accept({ ...event, sequence: 2 }), false, "disconnect rejects pending event");
assert.equal(applied, 1);
assert.throws(() => midiFaderConnection({ ...connection, input_session: 0 }));
const reconnected = { ...connection, input_session: 14 };
input.setConnection(reconnected);
faders.setOptimistic("2:Dimmer", 123);
assert.equal(input.accept({ ...event, ...reconnected, sequence: 1 }), true);
assert.equal(values["2:Dimmer"], 40000, "MIDI replaces settled GUI optimism");
let release;
const pending = faders.enqueue("2:Dimmer", 500, () => new Promise(resolve => release = resolve));
assert.equal(faders.applyMidiInput({ "2:Dimmer": 300 }), false, "editor ingress must also reject input during an owned GUI write");
assert.equal(values["2:Dimmer"], 500, "owned pending GUI write keeps ordering");
release(); await pending;
faders.clearAll();
assert.equal(faders.applyMidiInput({ "2:Dimmer": 300 }), true);
await new Promise(resolve => setTimeout(resolve, 210));
values = faders.mergeSnapshotValues(values, { "2:Dimmer": 320 });
assert.equal(values["2:Dimmer"], 320, "rejected input projection expires and canonical polling recovers");
const app = await fs.readFile(new URL("../src/App.tsx", import.meta.url), "utf8");
assert.match(app, /if \(!faderValueController\.applyMidiInput\(values\)\) return;/);
assert.match(app, /listen<unknown>\("syndocal:\/\/midi-fader-input-v1"/);
assert.doesNotMatch(app, /uiIntervalMs = midiControlConnected\(\) \? 50/);
const native = await fs.readFile(new URL("../src-tauri/src/main.rs", import.meta.url), "utf8");
assert.match(native, /if accepted && !ui_values\.is_empty\(\)/);
console.log("PASS: received MIDI updates immediately; project, session, sequence and payload fences; own-write ordering and bounded canonical recovery");
